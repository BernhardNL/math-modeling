add_p("局限三：bbox 标注的语义歧义与主观性。数据集的 bbox 标注本身存在语义模糊性——同一块大面积锈蚀，标注员可能用一个外接矩形框出全部区域，也可能用多个小框分别标注锈蚀斑块。训练集和测试集之间标注风格的不一致使得「正确检测」的定义本身就带有不确定性。滑动窗口方法无法学习到这种标注风格的规律，输出的规则网格框与人工标注的主观边界框天然存在形态差异。")

