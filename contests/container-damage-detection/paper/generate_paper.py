add_p("目标检测的数学本质是学习一个从图像空间到检测空间的条件分布 P(bbox, cls | I)。传统两阶段方法（Faster R-CNN）通过区域提议显式生成候选框，而 YOLO 系列采用稠密预测范式：将输入图像 I ∈ R^{640×640×3} 映射为多尺度特征图，在特征图的每个空间位置上直接回归边界框参数。")
add_p("YOLOv8 采用 Anchor-Free 公式化。设骨干网络输出的第 s 层特征图尺寸为 (H_s, W_s)，步长（stride）为 σ_s（即特征图上 1 个像素对应原图 σ_s×σ_s 区域）。对特征图上每个网格点 (i, j)，模型预测：")
add_p("（1）分类分数向量 ĉ ∈ R^C（C=3 为类别数），经 sigmoid 激活后表示该位置存在第 k 类目标的概率 p̂_k = σ(ĉ_k) = 1/(1+e^{-ĉ_k})；")
add_p("（2）边界框回归量 b̂ ∈ R^{4×N}（N=16 为 DFL 分布 bin 数），解码为网格点 (i,j) 到边界框四条边的距离 (l̂, t̂, r̂, b̂)。")
add_p("设网格点 (i,j) 在原图上的坐标为 (x_a, y_a) = (σ_s·(i+0.5), σ_s·(j+0.5))，则预测框为：x̂₁ = x_a − l̂, ŷ₁ = y_a − t̂, x̂₂ = x_a + r̂, ŷ₂ = y_a + b̂。相比基于锚框的方法，Anchor-Free 范式消除了锚框尺寸/宽高比的人工先验——这对本任务至关重要，因为残损框的宽高比分布从 1:1 的正方形到 1:8 的细长条均存在，任何固定的锚框先验都会引入系统性偏差。")
add_p("多尺度检测通过特征金字塔实现：YOLOv8 在 3 个尺度（P3/P4/P5，stride 8/16/32）上分别预测，覆盖从 8×8 到 640×640 的目标尺寸范围。本文进一步引入 P2 层（stride 4），将最小可检测目标扩展到 4×4 像素（详见 4.7.7 节）。")

add_h("4.7.2  网络结构：CSPDarknet 骨干与 PAN-FPN 颈部", 3)
add_p("YOLOv8 的骨干网络基于 CSPDarknet 架构，核心模块 C2f（CSP Bottleneck with 2 convolutions）实现跨阶段部分连接：输入特征 x ∈ R^{C×H×W} 经 1×1 卷积分为两路，一路直接传递（残差连接），另一路经 n 个 Bottleneck 单元处理后与直连支路在通道维拼接，再经 1×1 卷积融合。该设计的数学意义在于通过显式的梯度旁路缓解深层网络的梯度消失：设融合层输出 y = Conv(Concat(x_shortcut, F(x)))，则反向传播时 ∂L/∂x_shortcut 不经过 F 的深层变换，保证深层模块始终获得有效梯度信号。")
add_p("空间金字塔池化 SPPF（Spatial Pyramid Pooling Fast）通过串联的 3 个 5×5 最大池化将感受野从局部扩展到全局：第 k 次池化后的有效感受野为 (2k+1)×5 − k，三次池化后达到约 61×61 像素（在 P5 特征图上约覆盖 2000×2000 原图像素），使骨干末端特征同时携带局部纹理与全局上下文信息——这对大面积锈蚀（最大 bbox 面积 408,321 px²，接近全图）的检测尤为关键。")
add_p("颈部采用 PAN-FPN 双向特征融合结构：自顶向下路径（Top-down）通过上采样将高层语义特征传播至低层，自底向上路径（Bottom-up）通过下采样将低层空间细节回传至高层。设 P₅、P₄、P₃ 为骨干三个尺度的输出，融合后的特征可表示为：F₄ = C2f(Concat(P₄, Up(F₅))), F₃ = C2f(Concat(P₃, Up(F₄)))，再经反向路径 G₃ = F₃, G₄ = C2f(Concat(F₄, Down(G₃))), G₅ = C2f(Concat(P₅, Down(G₄)))。双向融合使每个检测头既具备高层语义判别力（识别\"这是锈蚀\"）又保留低层空间精度（定位\"锈蚀在哪里\"）。")
add_p("检测头采用解耦设计（Decoupled Head）：分类分支与回归分支各自独立的卷积序列，避免了两任务共享特征时的梯度冲突。分类分支输出 p̂_k = σ(ĉ_k)，回归分支输出 4×16 维的 DFL 分布参数（见 4.7.4 节）。")

add_h("4.7.3  标签分配：任务对齐学习（TAL）", 3)
add_p("Anchor-Free 范式下每个网格点都是候选锚点，训练时需要决定哪些锚点作为正样本参与损失计算。YOLOv8 采用任务对齐标签分配策略（Task-aligned Assigner），其核心是定义锚点与真实框之间的对齐度量：")
add_p("t = s^α × u^β")
add_p("其中 s 为锚点的分类分数（预测该锚点存在目标的置信度），u 为该锚点预测框与真实框的 IoU，α=0.5、β=6.0 为超参数。对齐度量同时考察分类质量和定位质量：一个理想的锚点必须既被分类分支\"识别\"为目标（s 高），又被回归分支\"定位\"准确（u 高）。对每个真实框，选择 t 值最大的 top-k 个锚点作为正样本（k=10），其余为负样本。")
add_p("正样本的目标分数（target score）设为分类分数与 IoU 的乘积 s×u（而非 1），该软标签机制使分类损失与定位质量耦合：定位不准确的锚点即使被分配为正样本，其目标分数也较低，分类分支会降低对该锚点的置信度输出。这一机制在推理阶段自然实现了\"定位差的预测框置信度低\"，减少了 NMS 前的高置信度误报。")

add_h("4.7.4  损失函数：DFL 分布焦点损失与总损失", 3)
add_p("YOLOv8 的边界框回归采用 Distribution Focal Loss（DFL），将\"框边到锚点的距离\"建模为离散概率分布而非单点估计。设真实距离为 y（l/t/r/b 之一），预测分布为 S = (S₀, S₁, …, S_{N−1})（N=16，经 softmax 归一化，对应 0 到 N−1 的整数值），DFL 损失为：")
add_p("L_DFL(S, y) = −[(y_{i+1} − y)·log S_i + (y − y_i)·log S_{i+1}]，其中 i = ⌊y⌋")
add_p("该损失鼓励概率质量集中在真实值 y 两侧的相邻 bin 上，而非仅匹配最接近的整数 bin。DFL 的理论动机在于：边界框回归本质上存在模糊性（真实边界本身带有标注噪声），将回归目标表示为分布能够显式建模这种不确定性——模型学到的分布越尖锐，说明该次预测越确定。这与本任务中残损边界标注的主观模糊性高度契合。回归分支的最终预测值为分布的期望：ŷ = Σ_{k=0}^{N−1} k·S_k。")
add_p("分类分支采用二元交叉熵（BCE）损失：L_cls = −(1/|Ω|)Σ_{i∈Ω}[t_i log p̂_i + (1−t_i) log(1−p̂_i)]，其中 Ω 为全部锚点集合，t_i 为 TAL 分配的目标分数（正样本 t_i = s×u，负样本 t_i = 0）。边界框损失采用 CIoU：L_box = 1 − IoU + ρ²(b, b^gt)/c² + αν，其中 ρ 为框中心距，c 为最小外接矩形对角线，αν 为长宽比一致性惩罚项。总损失为三个分量的加权和：")
add_p("L = λ_box·L_box + λ_cls·L_cls + λ_DFL·L_DFL，默认权重 λ_box=7.5, λ_cls=0.5, λ_DFL=1.5。")

add_h("4.7.5  改进一：Wise-IoU 距离注意力损失", 3)
add_p("CIoU 损失存在一个与本任务相关的缺陷：其对所有尺度的目标施加统一形式的长宽比惩罚，而集装箱破损检测中不同类别的\"定位难点\"具有显著差异——Rusty（锈蚀）类 bbox 平均面积最大（中位数 2978 px²，P90=16768 px²），且锈蚀区域的边界高度模糊，预测框中心容易偏离真实框中心；Dent/Hole 类目标较小但边界清晰，中心定位通常较准。CIoU 无法针对这种类别间定位难度差异进行自适应调整。")
add_p("Wise-IoU v1 通过引入基于中心距离的指数注意力因子解决这一问题。设预测框与真实框的中心分别为 (x,y) 与 (x_gt, y_gt)，真实框宽高为 (W_gt, H_gt)，定义距离注意力因子：")
add_p("R_WIoU = exp( (x−x_gt)² + (y−y_gt)² / (W_gt² + H_gt²) ) ∈ [1, e)")
add_p("则 Wise-IoU 损失为：L_WIoU = R_WIoU × (1 − IoU)。")
add_p("该形式的数学性质分析如下：")
add_p("（1）R_WIoU 的取值范围为 [1, e)：当预测框中心与真实框中心完全重合时 R_WIoU=1，退化为标准 IoU 损失；当中心距离达到真实框对角线长度时 R_WIoU→e≈2.718。上界 e 的存在保证了损失不会因极端离群样本而发散，训练稳定性得以维持。")
add_p("（2）注意力的尺度自适应性：分母 (W_gt² + H_gt²) 使中心距离惩罚按目标自身尺度归一化。对 200×200 的大锈蚀框，中心偏移 20 像素仅产生 R_WIoU ≈ exp(800/80000) ≈ 1.01 的温和惩罚；对 20×20 的小破洞框，同样的 20 像素偏移产生 R_WIoU ≈ exp(800/800) ≈ 2.72 的强惩罚。这种\"大目标容忍中心偏差、小目标严格要求中心对准\"的注意力机制与检测任务的物理直觉一致。")
add_p("（3）与传统 IoU 损失的对比：标准 L_IoU = 1 − IoU 仅度量重叠程度，对\"完全不重叠\"的任意预测给出相同的损失值 1，梯度无法区分\"中心偏离 10 像素\"与\"中心偏离 100 像素\"的预测。R_WIoU 因子为完全不重叠的预测提供了基于中心距离的连续梯度信号，使回归过程在早期（IoU=0 阶段）就能获得有效的下降方向，加速收敛并改善最终定位精度。")
add_p("（4）与 Rusty 类别性能的关联：Rusty 类在 CIoU 训练下 AP@0.5 仅 0.222，显著低于 Dent（0.456）和 Hole（0.503）。锈蚀标注框面积大、形状不规则、边界模糊，预测框中心与标注框中心的系统性偏差是 AP 损失的主要来源之一。Wise-IoU 对大面积框的温和惩罚使模型不必为匹配模糊边界而过度收缩预测框，从而保留更完整的锈蚀区域覆盖，直接改善 IoU≥0.5 的命中率。实验验证见 4.7.9 节（Rusty AP@0.5 提升 3.1 个百分点）。")

add_h("4.7.6  改进二：SlideLoss 滑窗加权分类损失", 3)
add_p("标准 BCE 分类损失对所有正样本一视同仁，但 TAL 分配的正样本在对齐质量上存在显著差异：对齐分数 t=s^α·u^β 接近 1 的\"简单正样本\"（分类准、定位准）与 t 接近 0.1 的\"困难正样本\"（分类或定位质量差）在梯度贡献上是相等的，导致训练后期梯度被大量简单样本主导，困难样本难以被充分学习。")
add_p("SlideLoss 的核心思想是以当前批次的前景样本平均对齐分数 μ 为基准，构造单调递减的权重函数，对简单样本降权、对困难样本加权。本文采用的权重函数为：")
add_p("w(t) = 0.5 + 0.5·tanh( 5(μ − t)/μ )，其中 μ = mean{ t_i | t_i > 0 }")
add_p("该函数的数学性质：")
add_p("（1）当 t = μ 时，w = 0.5，即平均难度的样本保持基准权重；")
add_p("（2）当 t → 0（极困难样本）时，w → 0.5+0.5·tanh(5) ≈ 0.9999，权重趋于上限 1；")
add_p("（3）当 t → 1（极简单样本）时，w → 0.5+0.5·tanh(−5/μ) ≈ 0.0001，权重趋于下限 0；")
add_p("（4）tanh 的饱和特性使权重函数在 μ 附近近似线性、在两端平滑饱和，避免了硬阈值切换（如标准 SlideLoss 的分段线性函数）带来的梯度不连续问题。")
add_p("加权后的分类损失为：L'_cls = (1/|Ω|)Σ_{i∈Ω} w(t_i)·[t_i log p̂_i + (1−t_i) log(1−p̂_i)]。该加权机制的自适应性体现在：μ 随训练进程动态变化——训练初期所有正样本对齐分数都低，μ 小，权重分布平坦；训练后期简单样本对齐分数升高，μ 增大，权重向困难样本集中。模型始终将学习资源分配给\"当前阶段最需要改进\"的样本，实现了软性的在线难例挖掘（OHEM），且无需额外的样本选择开销。")

add_h("4.7.7  改进三：P2 高分辨率小目标检测层", 3)
add_p("2.2.2 节的数据分析显示，训练集 bbox 的 P10 面积仅 609 px²（约 25×25 像素），最小标注框仅 4 px²（2×2 像素）。标准 YOLOv8 的最细检测尺度为 P3（stride=8），其特征图尺寸 80×80，对应原图 8×8 像素的检测粒度：面积小于 64 px² 的残损在 P3 特征图上不足 1 个像素的响应区域，其空间信息在多级下采样中已被不可逆地稀释。")
add_p("本文在标准 YOLOv8 基础上引入 P2 检测层（stride=4），形成 P2/P3/P4/P5 四级检测金字塔：")
add_p("（1）前向路径：在 PAN-FPN 的 P3 层（80×80）之上增加一级上采样，与骨干 P2 层输出（160×160，stride=4）拼接后经 C2f 融合，得到 P2 检测特征（160×160×128）；")
add_p("（2）反向路径：P2 特征经 3×3 卷积（stride=2）下采样后回传至 P3 层，与自顶向下路径的 P3 特征拼接，实现双向信息交换；")
add_p("（3）检测头：新增与 P2 对应的检测头，其输入特征图尺寸 160×160，每像素对应原图 4×4 区域，最小可检测目标从 8×8 降至 4×4 像素。")
add_p("P2 层的感受野分析：设 P2 检测特征的一个单元经骨干卷积链的累积感受野约为 15×15 原图像素，恰好匹配 P10~P25 面积区间（609~1611 px²，约 25×25 ~ 40×40 像素）的小残损尺寸——目标略大于感受野时，检测单元能同时感知目标整体与周围上下文，这是小目标检测的最优感受野配置。")
add_p("代价与权衡：P2 层使检测头的计算量增加约 30%（160×160 的特征图含 25,600 个锚点，超过 P3/P4/P5 锚点之和），且新增层的权重无法从 COCO 预训练模型迁移（需随机初始化），训练初期 P2 分支的预测质量较低。但 TAL 标签分配机制天然适应这种\"冷启动\"：P2 锚点只有在预测质量足够高时才会被分配为正样本，其梯度信号随训练进程自然增强，不会干扰已收敛的 P3/P4/P5 分支。")

