add_h("3.5.5  贝叶斯最小风险决策框架", 3)
add_p("鉴于 NP 框架在当前数据上的统计前提不成立（第 3.5.3–3.5.4 节），本节引入贝叶斯最小风险决策理论，从损失函数和代价权衡的角度重新建立阈值选择的方法论基础。与 NP 框架不同，贝叶斯最小风险决策不需要对 H₀ 下检验统计量的分布做任何参数假设，而是直接从决策的期望代价出发推导最优阈值。")
add_p("设决策空间 A = {a₀, a₁}，其中 a₀ 表示「判定图像无残损」，a₁ 表示「判定图像有残损」。状态空间 Y = {0, 1}，其中 0 为真实无残损，1 为真实有残损。定义损失函数 L(a, y) 为采取决策 a 而真实状态为 y 时的代价：")
add_p("    L(a₀, 0) = 0          （正确判定无损伤，无代价）")
add_p("    L(a₁, 0) = C_FP       （误报：将好箱判为坏箱）")
add_p("    L(a₀, 1) = C_FN       （漏检：将坏箱判为好箱）")
add_p("    L(a₁, 1) = 0          （正确判定有损伤，无代价）")
add_p("其中 C_FP > 0 为误报代价（触发不必要的人工复核），C_FN > 0 为漏检代价（破损集装箱被放行）。给定输入图像 x 及其逻辑回归输出的后验概率 p = P(y=1|x)，两个决策的期望损失（贝叶斯风险）分别为：")
add_p("    R(a₀ | x) = C_FN · p")
add_p("    R(a₁ | x) = C_FP · (1 − p)")
add_p("贝叶斯最优决策规则为选择期望损失最小的行动。判定 a₁（有损伤）当且仅当 R(a₁ | x) < R(a₀ | x)，即：")
