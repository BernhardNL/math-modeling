add_p("Neyman-Pearson（NP）引理为二元假设检验提供了最优决策准则。本文设定：H₀（零假设）：图像无残损；H₁（备择假设）：图像有残损。检验统计量取为逻辑回归输出的概率分数 s = P(y=1|x) ∈ [0,1]。NP 框架的决策规则为：给定显著性水平 α（I 类错误率——将无残损图像误判为有残损的概率上限），选择阈值 τ 使得在 H₀ 为真时，P(s > τ | H₀) ≤ α。即 τ = F^{-1}_{H₀}(1−α)，其中 F_{H₀} 为 H₀ 下检验统计量 s 的累积分布函数（CDF）。NP 框架的核心特征是仅控制 I 类错误（误报率），不直接控制 II 类错误（漏检率）。该非对称性适用于误报代价远高于漏检的场景（如医疗筛查、安全检测），但在集装箱破损检测中，漏检（未发现真实损伤）的后果可能比误报（多一次人工复核）更为严重，这一方向性差异将在后续分析中体现。")

