add_p("（1）天然支持多分类：采用 softmax 多分类目标，输出归一化的类别概率向量。")
add_p("（2）对类别不均衡鲁棒：通过 class_weight='balanced' 按类别样本频率的倒数对损失加权，Hole 等少数类的每个样本获得更高的损失权重，等价于在不改变数据分布的前提下实现代价敏感学习。")
add_p("（3）特征重要性可解释：训练后可输出基于分裂增益（gain）的特征重要性排序，便于分析哪些特征模块对分类贡献最大。")
add_p("（4）对特征尺度不敏感：基于直方图的分裂算法只依赖特征值的排序关系，特征的绝对尺度不影响分裂阈值的选择。但为保持与问题1方法论的一致性，仍进行 Z-score 标准化。")

add_h("4.3.2  模型原理", 3)
add_p("LightGBM 属于梯度提升框架（Friedman, 2001）：以加法模型 F(x) = Σ_{m=1}^{M} η·f_m(x) 逐轮拟合损失函数的负梯度方向，其中 f_m 为第 m 轮训练的决策树，η 为学习率（shrinkage），M 为树的数量。算法流程如下：")
add_p("Step 1（多分类损失）：对 K=4 类分类任务，采用带类别权重的 softmax 交叉熵损失 L = −Σ_{i}Σ_{k=1}^{K} w_k·y_ik·log p_ik，其中 p_ik = softmax(F_k(x_i)) 为第 i 个样本属于第 k 类的预测概率，w_k 为类别权重（class_weight='balanced'，w_k = N/(K·N_k)，N_k 为第 k 类样本数）。类别权重使少数类（Hole，仅 788 个训练样本）的单样本误分类代价按比例放大，缓解类别不均衡。")
add_p("Step 2（负梯度拟合）：第 m 轮拟合的目标是损失函数对当前模型输出的负梯度（伪残差）r_ik = −∂L/∂F_k(x_i) = w_k(y_ik − p_ik)。直观上，当前模型把第 i 个样本判为第 k 类的概率越低，其残差越大，下一棵树越着力「修正」该样本——与 AdaBoost 的样本加权思想异曲同工，但通过对损失函数的函数空间梯度下降实现，可适配任意可微损失。")
add_p("Step 3（直方图算法与叶向生长）：每棵树分裂前先将特征值离散化为 256 个 bin 的直方图，仅在 bin 边界处搜索最优分裂点，使单次分裂的计算复杂度从 O(#data × #features) 降至 O(#bins × #features)。树结构采用叶向（leaf-wise）生长——每次选择当前所有叶子中分裂增益最大的叶子进行分裂，直至叶子数达到 num_leaves=63 或叶内样本数低于 min_child_samples=20。分裂增益由牛顿法导出：Gain = ½[G_L²/(H_L+λ) + G_R²/(H_R+λ) − (G_L+G_R)²/(H_L+H_R+λ)]，其中 G、H 分别为叶子内样本损失的一阶、二阶梯度之和，λ 为正则化系数。叶向生长配合不限制深度（max_depth=−1）的策略，使树能针对少数难分区域「定向加深」，比逐层生长更高效地拟合复杂的非线性决策边界。")
add_p("Step 4（集成预测）：最终输出 F(x) = Σ_{m=1}^{M} η·f_m(x)，类别概率 p_k = softmax(F_k(x))，分类结果 ŷ = argmax_k p_k。学习率 η=0.1 的收缩机制使每棵树只贡献小幅修正，防止单棵树过拟合主导模型。")
add_p("超参数配置：n_estimators=1000（树的数量）、num_leaves=63（每棵树最大叶子数）、learning_rate=0.1（shrinkage）、max_depth=−1（不限制深度）、min_child_samples=20（叶内最小样本数）、class_weight='balanced'。该配置由 3 维网格搜索确定（见 4.6.2 节）。")

